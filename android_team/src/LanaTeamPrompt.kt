package ai.dreibus.lanalive

internal object LanaTeamPrompt {
    const val MAX_TASK = 1000
    private val context = """
        Проект LANA — Android-приложение голосового ИИ-помощника и координатора API-команды, не человек-менеджер. Цель: голосовой диалог без повторного нажатия, состояния Слушаю/Думаю/Отвечаю, задачи, память и журнал результатов; позже работа с выключенным экраном и 24/7.
        Реализованы: возврат к слушанию, локальные часы, шифрованное сохранение подключения, отправка задания OpenAI через существующий сервер, журнал и ручное подтверждение результата. Добавлены голосовые задания OpenAI, локальные заметки/задачи и экспериментальный фон; фон ещё не проверен на устройстве. Их наличие не доказывает устойчивость на устройстве. Claude и Manus не подключены. История этого чата ChatGPT и файлы проекта автоматически недоступны; переданы только этот контекст и явно выбранные заметки.
        Нужны технические шаги разработки приложения, не советы по мотивации людей. Не выдумывай доступ к коду, тесты или выполненные действия. GOLD/Kraken не трогать; остановка служб требует согласования. Для задачи о развитии дай 3 коротких шага: изменение, ожидаемый результат, конкретная проверка. Отделяй подтверждённое от предположений. Ответ до 110 слов, чтобы он поместился в лимит сервера.
        Задание пользователя:
    """.trimIndent() + "\n"

    fun build(task: String): String {
        require(task.isNotBlank() && task.length <= MAX_TASK)
        return (context + task).also { require(it.length <= 2400) }
    }
}
