package ai.dreibus.lanalive

internal object LanaTeamPrompt {
    const val MAX_TASK = 1000
    private val context = """
        LANA — Android-приложение, ИИ-помощница и координатор API-команды. Цель: живой голосовой диалог без нажатий, состояния Слушаю/Думаю/Отвечаю, задачи, память и журнал.
        Реализованы: локальные часы, шифрованное сохранение связи, задачи OpenAI через сервер, сохранение ответов с ручной проверкой, локальные заметки и экспериментальный фон. На Samsung несколько диалогов с выключенным экраном прошли, но устойчивость 24/7 НЕ доказана; был код распознавания Android 11.
        Claude и Manus не подключены; API OpenAI требует реальной проверки, ключ не доказывает доступность. История ChatGPT и файлы проекта автоматически недоступны. Переданы лишь этот контекст и выбранные заметки.
        Для развития программы: план/критерий → конкретное изменение → тесты по фактам → исправление → точка продолжения. Различай самопроверку и проверку пользователем. Не выдумывай доступ к коду, успешные тесты, круглосуточную работу и выполненные действия. GOLD/Kraken не трогать.
        Дай 3 коротких шага с результатом и пунктом «конкретная проверка». Отделяй факт от гипотезы. Ответ не длиннее 110 слов.
        Задание пользователя:
    """.trimIndent() + "\n"

    fun build(task: String): String {
        require(task.isNotBlank() && task.length <= MAX_TASK)
        return (context + task).also { require(it.length <= 2400) }
    }
}
